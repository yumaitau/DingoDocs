import { writeFile } from "node:fs/promises";

const distribution = process.env.DINGODOCS_DISTRIBUTION ?? "development";
if (!["development", "community", "aws-marketplace"].includes(distribution))
  throw new Error(`Unsupported DingoDocs distribution: ${distribution}`);

const identity = {
  productCode: (process.env.AWS_MARKETPLACE_PRODUCT_CODE ?? "").trim(),
  productSku: (process.env.AWS_MARKETPLACE_PRODUCT_SKU ?? "").trim(),
  contractDimension: (
    process.env.AWS_MARKETPLACE_CONTRACT_DIMENSION ?? ""
  ).trim(),
  keyFingerprint: (
    process.env.AWS_MARKETPLACE_LICENSE_FINGERPRINT ?? ""
  ).trim(),
};
if (
  distribution === "aws-marketplace" &&
  Object.values(identity).some((value) => !value)
)
  throw new Error(
    "Marketplace image builds require product code, SKU, dimension, and fingerprint",
  );

const source = `// Generated by scripts/embed-marketplace-identity.mjs during image builds.
// Runtime environment variables cannot change these compile-time values.
export const GENERATED_DISTRIBUTION = ${JSON.stringify(distribution)};
export const GENERATED_MARKETPLACE_IDENTITY = ${JSON.stringify(identity, null, 2)} as const;
`;
await writeFile("src/lib/marketplace/aws/identity.generated.ts", source);
